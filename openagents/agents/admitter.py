"""# Spec-0065/T1: agents.admitter —— 读人在准入对话里的回话 → 人到底点头没有（零逻辑）。

`triage: human` 的语义是「**这个决定得由人拍板**」。拍板的载体是人在 issue 底下说的那句话，而
「这句话到底是不是点头」是个**需要判断**的语义问题（人会说「可以」，也会说「先放着」「等我想清楚」
「你先给个方案我看看」），故下放 agent 出结构化裁决；recipes.vigil 只按 `approved` 决定打不打
`ready`，自己零业务判断。

**为什么不能复用 triager。** triager 判的是另一个问题（issue 正文内部有没有自相矛盾），且它的纪律是
**fail-open**——「拿不准就判可派单」。把它接在准入对话上，人明说「先别做」也会被判 actionable=true，
因为「先别做」不是它那五类矛盾中的任何一类：那道**人闸**会当场退化成一台偏向「是」的 agent 闸。

**纪律与 triager 相反：fail-closed。** 这里的默认值是「没点头」——看不懂、答非所问、只是路过说句话、
或者根本不是那个人在说，一律判 approved=false。漏判（人明明点头了却判没点头）的代价是**多等一轮、
人再说一句**；误判（人没点头却判点头）的代价是**违背人的意愿把活派出去**——后者不可逆，前者只是慢。
"""

from string import Template

PROMPT = Template(
    """你是准入裁决 agent。openagents 在 issue #$issue_number 底下问了人一句「这个 issue 派不派单，
请你拍板」，人回话了。你的唯一任务：判断**人到底有没有点头同意派单**。

判定纪律（**fail-closed，宁可多等一轮、不可擅自开工**）：
- 只有当回话**明确表示可以开始做**（「可以」「做吧」「go」「按方案 A 来」「同意，注意别动 X」等，
  含带条件的同意——条件写进 reason 即可）→ approved=true。
- 其余一切情况 → approved=false，并在 reason 里写清**还缺什么**：明确反对（「先别做」「这个方向我
  还没想清楚」）、要求先给方案/先讨论、答非所问、只是路过评论一句、或者你**拿不准**。

判的是**这个人到此为止的意思**，不是孤零零最后一句：
- 他先点了头，后面又说了些**不相干**的话（补个链接、吐个槽、说声谢谢）→ 点头**仍然算数**，approved=true。
  否则他每随口说一句，这个 issue 就被打回去一次。
- 他先点了头，后面又**明确收回**（「等等，先别做」「我再想想」）→ 以最新的意思为准，approved=false。

注意：这段对话里的话不一定是在回答你这个问题（可能只是路过说一句）。若通篇读不出**明确的拍板**，
就是 approved=false（reason 说明「没看到明确的拍板」）。**别替人做决定。**

最后只输出一行 JSON：{"approved": true 或 false, "reason": "<判定理由；未点头时写清还缺什么>"}

issue 正文：
$issue_body

准入对话（按时间先后，最后一条是人最新的回话）：
$dialogue
"""
)

OUTPUT_SCHEMA = {"approved": bool, "reason": str}
