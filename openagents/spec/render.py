"""Generate the Spec overview, task board, dependency graphs, and ownership report."""

from __future__ import annotations

from pathlib import Path

from openagents.spec import model
from openagents.spec.model import Group, Task

# Spec-0014/T3: Evolved node to color by status (pending/in-progress/done/abandoned).
_STATUS_FILL = {
    "pending": "#eeeeee",
    "in-progress": "#fff3b0",
    "done": "#b7e4c7",
    "abandoned": "#f4b8b8",
}

# Spec-0014/T3: Fixed title, which allows for the assertion that "all parts are all together".
# Spec-0015/T4: TL; top DR block header (same to _BOARD_HEADING to test the existence of the asserted block).
_TLDR_HEADING = "## TL;DR"
_BOARD_HEADING = "## Task board"
_RELATION_HEADING = "## Cross-Spec relationships"
_CONFLICT_HEADING = "## File ownership overlaps"
_FEATURE_HEADING = "## Spec details"


def render(*, specs_root: Path) -> str:
    """Render the full OVERVIEW.md text from a specs tree (pure, idempotent).

    Spec-0014/T3: The pure function returns the full text; the empty warehouse returns the skeleton with only four headers, without error.
    """
    groups = model.load_all(specs_root=specs_root)
    blocks = [
        "# Spec overview",
        "> Generated by `spec render`. Do not edit by hand (Spec-0014/T3).",
        _render_tldr(
            groups=groups
        ),  # Spec-0015/T4: Top person's voice-show, ahead of the global board.
        _render_board(groups=groups),
        _render_relations(groups=groups),
        _render_conflicts(groups=groups),
        _render_features(groups=groups),
    ]
    # Uniformity is linked by single line-to-line, and the whole ends by a line-to-line line, guaranteeing certainty.
    return "\n\n".join(blocks).rstrip("\n") + "\n"


def write_overview(*, specs_root: Path) -> Path:
    """Render and write docs/specs/OVERVIEW.md, returning its path.

    Spec-0014/T3: Sender+Close to specs_root/OVERVIEW.md.
    """
    path = specs_root / "OVERVIEW.md"
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(render(specs_root=specs_root), encoding="utf-8")
    return path


def _render_tldr(*, groups: list[Group]) -> str:
    """Block 0: TL; DR Top Snippet - Spec-0015/T4.

    Before you look at the board, you don’t have to read the secret form to see what every feauty is doing.
    Empty storage is only entitled (bones) and is not misreported; and thall is sorted by a defined group with _cell.
    """
    lines = [_TLDR_HEADING]
    for group in groups:
        title = group.metadata.title or group.metadata.slug
        lines.append("")
        lines.append(f"### {group.number} {_cell(title)}")
        lines.append(_cell(group.metadata.summary))
        # Spec-0040/T1: Declared e2e 's rough plan group, and inserted the phrase "intent + acceptance behaviour" in TL; DR (persons see this at first glance)
        # How does this work, concept 8?
        lines.extend(_render_e2e(group=group))
    return "\n".join(lines)


def _render_e2e(*, group: Group) -> list[str]:
    """Spec-0055/T2: Render group e2e measurements to TL; two rows of ”e2e intent + prose measurement” in DR.

    e2e does not declare return to empty list (no behavior change); the declaration output one line of intent + one line of measurement (method multiline proce by _cell
    Enter a single line summary. Pure function, _cell is a security, etc. (`spec render` is not drifted).
    """
    e2e = group.metadata.e2e
    if e2e is None:
        return []
    return [
        f"- End-to-end intent: {_cell(e2e.intent)}",
        f"  - Method: {_cell(e2e.method)}",
    ]


def _render_board(*, groups: list[Group]) -> str:
    """Block 1: global view of the table, one current version per line, Task."""
    lines = [
        _BOARD_HEADING,
        "",
        "| Group | Task | Title | Status | Dependencies | Files |",
        "|----|----|----|----|----|----|",
    ]
    for group in groups:
        for task in group.tasks:
            qid = model.qualified_id(group=group.number, task_id=task.id)
            deps = ", ".join(task.depends_on) or "—"
            files = "<br>".join(task.files) or "—"
            lines.append(
                f"| {group.number} | {qid} | {_cell(task.title)} | {task.status} | {deps} | {files} |"
            )
    return "\n".join(lines)


def _render_relations(*, groups: list[Group]) -> str:
    """Block 2: Crossfeature Relationship Map (Mermaid, subgraph/feature; decends-on-line, relates-to-fault line)."""
    lines = [_RELATION_HEADING, "", "```mermaid", "graph LR"]
    current_ids = {
        model.qualified_id(group=g.number, task_id=t.id) for g in groups for t in g.tasks
    }
    # 1. Each feature one subgraph, which contains its current version of the Task node.
    for group in groups:
        lines.append(f"    subgraph G{group.number}[{group.number} {group.metadata.slug}]")
        for task in group.tasks:
            qid = model.qualified_id(group=group.number, task_id=task.id)
            lines.append(f'        {_node(qid)}["{task.id} {_cell(task.title)}"]')
        lines.append("    end")
    # 2. Depends-on solid line edge (degraded to limited ID; only with nodes).
    for group in groups:
        for task in group.tasks:
            src = model.qualified_id(group=group.number, task_id=task.id)
            for ref in task.depends_on:
                dst = _resolve(ref=ref, group=group.number)
                if dst in current_ids:
                    lines.append(f"    {_node(src)} --> {_node(dst)}")
    # 3. Relates-to dotted line edges (typ).
    for group in groups:
        for task in group.tasks:
            src = model.qualified_id(group=group.number, task_id=task.id)
            for rel in task.relates_to:
                dst = _resolve(ref=rel.ref, group=group.number)
                if dst in current_ids:
                    lines.append(f"    {_node(src)} -.{rel.type}.-> {_node(dst)}")
    lines.append("```")
    return "\n".join(lines)


def _render_conflicts(*, groups: list[Group]) -> str:
    """Block 3: Document conflict reports - The same document is occupied by 2 groups of thorium (cooperative signals)."""
    # File-> Encumbers its set number.
    owners: dict[str, set[str]] = {}
    for group in groups:
        for task in group.tasks:
            for path in task.files:
                owners.setdefault(path, set()).add(group.number)

    conflicts = {path: nums for path, nums in owners.items() if len(nums) > 1}
    lines = [_CONFLICT_HEADING, ""]
    if not conflicts:
        lines.append("No files are shared across groups.")
        return "\n".join(lines)
    lines.extend(["| File | Groups |", "|----|----|"])
    for path, nums in sorted(conflicts.items()):
        lines.append(f"| {path} | {', '.join(sorted(nums))} |")
    return "\n".join(lines)


def _render_features(*, groups: list[Group]) -> str:
    """Block 4: For each feature segment - inside group view + relies on DAG + evolution."""
    lines = [_FEATURE_HEADING]
    for group in groups:
        title = group.metadata.title or group.metadata.slug
        lines.append("")
        lines.append(f"### {group.number} {title} (issue #{group.metadata.issue})")
        lines.append("")
        lines.append(_render_group_dag(group=group))
        lines.append("")
        lines.append(_render_evolution(group=group))
    return "\n".join(lines)


def _render_group_dag(*, group: Group) -> str:
    """Group dependent on DAG (Mermaid); take over when no mission takes place."""
    lines = ["```mermaid", "graph LR"]
    ids = {task.id for task in group.tasks}
    for task in group.tasks:
        lines.append(f'    {_node(task.id)}["{task.id} {_cell(task.title)}"]')
    for task in group.tasks:
        for ref in task.depends_on:
            # DAG is only dependent within the group (incorporated in the global relationship map).
            if "/" not in ref and ref in ids:
                lines.append(f"    {_node(ref)} --> {_node(task.id)}")
    if not group.tasks:
        lines.append("    empty[No tasks]")
    lines.append("```")
    return "\n".join(lines)


def _render_evolution(*, group: Group) -> str:
    """Evolution graph: Node = a Task version, colouring by status, and lined with blood fields."""
    lines = ["Evolution graph:", "", "```mermaid", "graph LR"]

    # 1. Summarize the sequence of each of the versions of each of the tasks (historical + current version), and the current nodes are easily attached to the lineage.
    versions = _task_versions(group=group)
    used_status: set[str] = set()
    node_class: list[str] = []

    # 2. Node declaration + redefined chain with the task version.
    for task_id in sorted(versions):
        chain = versions[task_id]
        for snapshot in chain:
            node_id = _ver_node(task_id=task_id, version=snapshot.version)
            lines.append(f'    {node_id}["{task_id} v{snapshot.version}"]')
            used_status.add(snapshot.status)
            node_class.append(f"    class {node_id} st_{_safe(snapshot.status)};")
        for older, newer in zip(chain, chain[1:], strict=False):
            lines.append(
                f"    {_ver_node(task_id=task_id, version=older.version)} "
                f"-->|redefined| {_ver_node(task_id=task_id, version=newer.version)}"
            )

    # 3. Slit / strengthened / children / developed: Source task latest edition  →  nask first edition.
    lines.extend(_lineage_edges(versions=versions))

    # Colored classDef (sole declaration of status, guarantee of certainty).
    for status in sorted(used_status):
        fill = _STATUS_FILL.get(status, "#ffffff")
        lines.append(f"    classDef st_{_safe(status)} fill:{fill};")
    lines.extend(node_class)
    lines.append("```")
    return "\n".join(lines)


def _task_versions(*, group: Group) -> dict[str, list[Task]]:
    """Each task_id version of the sequence (historical version by version + current version) is used for the evolution of the map."""
    all_ids = set(group.history) | {task.id for task in group.tasks}
    current = {task.id: task for task in group.tasks}
    result: dict[str, list[Task]] = {}
    for task_id in all_ids:
        chain = sorted(group.history.get(task_id, []), key=lambda t: t.version)
        if task_id in current:
            chain = [*chain, current[task_id]]
        result[task_id] = chain
    return result


def _lineage_edges(*, versions: dict[str, list[Task]]) -> list[str]:
    """From the latest of the Talsk blood fields: the latest of the source  →  this first edition of the task."""
    edges: list[str] = []
    for task_id in sorted(versions):
        chain = versions[task_id]
        if not chain:
            continue
        latest = chain[-1]
        first_node = _ver_node(task_id=task_id, version=chain[0].version)
        specs = [
            ("split", [latest.split_from] if latest.split_from else []),
            ("merged", latest.merged_from),
            ("supersedes", latest.supersedes),
            ("derived", latest.derived_from),
        ]
        for label, refs in specs:
            for ref in refs:
                src_id = ref.split("/")[-1]  # Evolution group, take the last slot
                if src_id in versions and versions[src_id]:
                    src_node = _ver_node(task_id=src_id, version=versions[src_id][-1].version)
                    edges.append(f"    {src_node} -->|{label}| {first_node}")
    return edges


def _resolve(*, ref: str, group: str) -> str:
    """Group short short  →  cap ID."""
    return ref if "/" in ref else model.qualified_id(group=group, task_id=ref)


def _node(qid: str) -> str:
    """Limit ID  →  to a valid Mermaid node name (n + non-alphagus + underline)."""
    return "n" + _safe(qid)


def _ver_node(*, task_id: str, version: int) -> str:
    """Evolution chart version node names."""
    return f"v_{_safe(task_id)}_{version}"


def _safe(text: str) -> str:
    """Convert any string into Mermaid security sign (non-letter numeral underlined)."""
    return "".join(ch if ch.isalnum() else "_" for ch in text)


def _cell(text: str) -> str:
    """Table / Node Label Unit: Press into single-line, transposition vertical lines."""
    return text.strip().replace("\n", " ").replace("|", "\\|").replace('"', "'")
