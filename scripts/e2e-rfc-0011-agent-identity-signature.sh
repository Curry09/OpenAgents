#!/usr/bin/env bash
# RFC-0011 peer-to-end test startup script: Local agent identity + comment signature (distinguishing from vs real person comment).
#
# Two paragraphs:
#   1) Offline certainty (default execution) - ruff lint/format + pytest, full mock, not touch the true gh.
#      Overwrite identity round-trip signature/lysis, state agent_id persever, msages self-review filters+ cursor simplified,
#      orchestrator/rebase back-stamp, cli-wire consistency, and current_login are offline.
#   2) True Signing Roundup Exercise (opt-in) - On a real PR when set up OPENAGENTS_E2E_REAL =1
#      Send a comment with a hidden signature with identity.post_signed_comment, and pass `gh pr view --json comments`
#      Take the original body back, assert that parse_agent_id can decipher this example agent_id (proves that the signature can go through gh,
#      GitHub is not visible but readable.
#
# Usage:
#   rash scripts/e2e-rfc-0011-agent-identity-signature.sh# Offline Only
#   OPENAGENTS_E2E_REAL = 1 E2E_PR = <PR Number > bash scripts/e2e-rfc-0011-agent-identity-signature.sh
#
# Optional environment variable (real exercise session):
#   E2E_PR target open PR number (really filled in for real exercise).
#   OPENAGENTS_AGENT_ID-Specify this instance agent_id (discussed/generated by resolve_agent_id).
set -euo pipefail

cd "$(dirname "$0")/.."

echo "==> [1/2] Offline certainty verification (%2)lint + format + Units/Integrated Test)"
uv sync --extra dev   # Ensure ruff / pytest In position (with .github/workflows/ci.yml Synchronize policy alignment)
uv run ruff check .
uv run ruff format --check .
uv run pytest -q

if [[ "${OPENAGENTS_E2E_REAL:-0}" != "1" ]]; then
  echo
  echo "✓ Offline validation passed. Real signature roundup has been skipped (set) OPENAGENTS_E2E_REAL=1 Open."
  exit 0
fi

echo
echo "==> [2/2] Real signature round-trip exercise:post_signed_comment → gh Fetch → parse_agent_id Parsing"
command -v gh >/dev/null || { echo "Require installation and login gh CLI"; exit 1; }
gh auth status >/dev/null || { echo "gh Not registered, please first. gh auth login"; exit 1; }
pr="${E2E_PR:?Please set E2E_PR=<Objective open PR Numbering>}"

# Send a signed comment on the target PR and assert that gh recovered original body can be parsed back by parse_agent_id to the same id.
uv run python - "$pr" <<'PY'
import sys

from openagents import github, identity
from openagents.state import State

pr_number = int(sys.argv[1])

# Parsing this instance agent_id (env > state > generate a drop-down disk), which is the same as the CLI connection.
state = State(path=__import__("pathlib").Path(".openagents/state.json"))
agent_id = identity.resolve_agent_id(state=state)
print(f"--> This instance agent_id = {agent_id!r}")

marker = "e2e-0011 Signing to and from the Quick"
identity.post_signed_comment(pr_number=pr_number, body=marker, agent_id=agent_id)
print(f"--> Already PR #{pr_number} Send signed comments")

# gh, retrieve the original body, find the new one, assert that the signature is typified and equals this example id.
comments = github.list_comments(pr_number=pr_number)
mine = [c for c in comments if marker in c.body and identity.parse_agent_id(body=c.body) is not None]
if not mine:
    print("✗ Not here. PR Found a signback on it")
    sys.exit(1)
latest = max(mine, key=lambda c: c.created_at)
parsed = identity.parse_agent_id(body=latest.body)
if parsed != agent_id:
    print(f"✗ Signing Resolution Unharmonious: Retrieving {parsed!r} != This instance {agent_id!r}")
    sys.exit(1)
print(f"    ✓ Sign through. gh To and from:parse_agent_id = {parsed!r}（== This instance agent_id）")
print(f"    ✓ The comment will be next. poll Scratch by signature, not trigger self-cycle")
PY

echo
echo "✓ Real signature round-trip exercise completed: self-reviewed signature available gh The Quest is a very important tool for the development of the country.poll From this,/Not by yourself."
echo "  Note: This script will be PR #$pr Leave a test comment, please clean up as necessary."
